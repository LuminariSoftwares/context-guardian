#!/usr/bin/env python3
"""gen_mcp_reference.py -- render the README's MCP tool reference from cg_mcp.TOOLS.

    python tools/gen_mcp_reference.py           print the reference
    python tools/gen_mcp_reference.py --write   replace the block in README.md
    python tools/gen_mcp_reference.py --check   exit 1 when README.md is out of date

The block sits between the two MARKERS below. tests/test_glama_quality.py runs
the same check, so a schema change without a README update fails the suite.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import cg_mcp  # noqa: E402

README = ROOT / "README.md"
START, END = "<!-- mcp-tools:start (generated by tools/gen_mcp_reference.py) -->", "<!-- mcp-tools:end -->"
HINTS = ("readOnlyHint", "destructiveHint", "idempotentHint", "openWorldHint")


def _md(text: str) -> str:
    """Escape `<` outside code spans, so GitHub does not read `<run>` as an HTML tag."""
    parts = str(text).split("`")
    return "`".join(p if i % 2 else p.replace("<", "&lt;") for i, p in enumerate(parts))


def _cell(text: str) -> str:
    return _md(text).replace("|", "\\|").replace("\n", " ")


def _constraints(spec: dict) -> str:
    parts = []
    for key, label in (("minLength", "min length"), ("minimum", "min"), ("maximum", "max"),
                       ("pattern", "pattern")):
        if key in spec:
            value = spec[key]
            parts.append(f"{label} `{value}`" if key == "pattern" else f"{label} {value}")
    return ", ".join(parts) or "none"


def render() -> str:
    out = []
    for tool in cg_mcp.TOOLS:
        ann = tool["annotations"]
        schema = tool["inputSchema"]
        required = set(schema.get("required", []))
        out.append(f"#### `{tool['name']}` ({tool['title']})")
        out.append("")
        out.append(_md(tool["description"]))
        out.append("")
        out.append("Annotations: " + ", ".join(f"`{h}: {str(ann[h]).lower()}`" for h in HINTS) + ".")
        out.append("")
        props = schema.get("properties", {})
        if not props:
            out.append("Parameters: none.")
        else:
            out.append("| parameter | type | required | default | constraints | example | description |")
            out.append("|---|---|---|---|---|---|---|")
            for name, spec in props.items():
                default = json.dumps(spec["default"]) if "default" in spec else "—"
                example = json.dumps(spec["examples"][0]) if spec.get("examples") else "—"
                out.append(f"| `{name}` | {spec['type']} | {'yes' if name in required else 'no'} | "
                           f"{_cell(default)} | {_cell(_constraints(spec))} | `{_cell(example)}` | "
                           f"{_cell(spec['description'])} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def readme_block(text: str) -> str:
    return text[text.index(START) + len(START):text.index(END)].strip("\n") + "\n"


def main(argv=None) -> int:
    args = sys.argv[1:] if argv is None else argv
    text = README.read_text(encoding="utf-8")
    if "--check" in args:
        if readme_block(text) != render():
            print("README.md MCP tool reference is out of date: run "
                  "python tools/gen_mcp_reference.py --write", file=sys.stderr)
            return 1
        return 0
    if "--write" in args:
        head, tail = text[:text.index(START) + len(START)], text[text.index(END):]
        README.write_text(head + "\n" + render() + "\n" + tail, encoding="utf-8", newline="\n")
        return 0
    sys.stdout.write(render())
    return 0


if __name__ == "__main__":
    sys.exit(main())
